#!/usr/bin/env python3
"""Generate programs/petri.cfg — the open world as a toy.

Top-down dish, true gated mechanics: a logical cell is two columns
[matter|law]. Every species rule is gated on the species' law glyph
in the cell's own law slot; expansion writes matter into the target
cell AND stamps the law slot (inheritance); miscopy mutants write
the TARGET species' seed instead (hopeful monsters, magenta flash).
Wound byte p erases matter (law ghosts remain until overwritten),
q erases law (matter fossilizes). Food pellets `o` are dropped by
wandering plankton `,` and make expansion toward them faster. The
player is a crosshair `+` ($-tunnel, transient) whose actions hit
the cell to its RIGHT: x smite, f feed, 1-4 plant, r restart.

Species:
  blaze R / law a (red)    expands 4-dir, can overwrite fern+drift
  fern  F / law b (green)  fast expansion into empty/food only
  drift ^>v< heads, C trail / law c (blue)  crawling streamers,
                                            turn clockwise on block
  stone S / law d (yellow) very slow creep, blaze cannot eat it

All rule scores are blank (0) — scoring to be decided later.
Run: python3 experiments/openworld/gen_petri.py
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parents[1] / "programs" / "petri.cfg"

EPS_W = "0.02"
SEEDS = {"blaze": ("R", "a", "1"), "fern": ("F", "b", "2"),
         "drift": (">", "c", "4"), "stone": ("S", "d", "3")}
MUT_FORE = "5"

L = []


def rule(head_, *body):
    L.append(head_)
    L.extend(body)


def head(lhs, trig, rep, fore, back="8", f6=None, f7=None, w=None,
         snd="="):
    h = "=" + snd + lhs + trig + rep + fore + back
    if f6 is not None or f7 is not None or w is not None:
        h += (f6 or " ") + (f7 or " ")
    if w is not None:
        h += " 0 " + w
    return h


# --- directional cell templates --------------------------------------
# Anchor is the matter slot; the cell's law slot is at (0,+1); the
# 4 neighbouring CELLS are at (0,±2) and (±1,0). g: own law glyph
# (literal gate read), ctx: target-matter context char, tm/tg:
# matter+law written into the target cell.
def exp_bodies(g, ctx, tm, tg):
    return {
        "E": [f"@{g}{ctx}@@ {tm}{tg}"],
        "W": [f"{ctx} @{g}@{tm}{tg}@"],
        "N": [f"{ctx}  {tm}{tg}", f"@{g}@@"],
        "S": [f"@{g}@@", f"{ctx}  {tm}{tg}"],
    }


def turn_bodies(g):
    return {
        "E": ["@" + g + "!@@"],
        "W": ["! @" + g + "@@"],
        "N": ["!", "@" + g + "@@"],
        "S": ["@" + g + "@@", "!"],
    }


def expansions(m, g, ctx, tm, tg, fore, w=None, f6=None, f7=None):
    for body in exp_bodies(g, ctx, tm, tg).values():
        rule(head(m, "T", m, fore, f6=f6, f7=f7, w=w), *body)


def species_block(name, others, w_empty=None):
    m, g, fore = SEEDS[name]
    expansions(m, g, "~", m, g, fore, w=w_empty)
    expansions(m, g, "o", m, g, fore, w="4")
    for other in others:
        tm, tg, _f = SEEDS[other]
        expansions(m, g, "~", tm, tg, MUT_FORE, w=EPS_W)


L += [
    "#!Petri  steps={steps}   {help}",
    "# Generated by experiments/openworld/gen_petri.py — do not edit",
    "# by hand. The open world (experiments/openworld/) as a toy:",
    "# cells are [matter|law] column pairs; law is inherited by",
    "# expansion, miscopies flash magenta, wounds hit matter (p) or",
    "# law (q, leaves fossils). Plankton motes drop food pellets.",
    "#help wasd+cross acts on cell to its right: x=smite f=feed"
    " 1234=plant | p/q=wound r=restart",
    "#threads 1",
    "#grid 2 1",
    "#transient +",
    "#timing i 0",
    "#timing T 60",
    "#timing e 240",
    "#timing p 1000",
    "#timing q 2200",
    "#control X clear",
    "^+uC",
    "^Ycl",
    "^ZcR",
    "^GcC",
    "^,uX",
    "^,lX",
]

# --- starters (one-shot on the boot timing) --------------------------
rule(head("Y", "i", "R", "1"), "@@@a")
rule(head("Z", "i", "F", "2"), "@@@b")
rule(head("G", "i", ">", "4"), "@@@c")

# --- blaze: expands, and overwrites fern or drift trail --------------
species_block("blaze", ("fern", "drift", "stone"))
for body in exp_bodies("a", "%", "R", "a").values():
    rule(head("R", "T", "R", "1", f6="F", f7="C", w="0.12"), *body)

# --- fern: fast, polite ----------------------------------------------
species_block("fern", ("blaze", "drift", "stone"), w_empty="2")

# --- drift: crawling heads, clockwise turns --------------------------
HEADINGS = {">": ("E", "v"), "v": ("S", "<"), "<": ("W", "^"),
            "^": ("N", ">")}
for hg, (d, nxt) in HEADINGS.items():
    rule(head(hg, "T", "C", "4", f6="~", f7="o"),
         *exp_bodies("c", "%", hg, "c")[d])
    rule(head(hg, "T", nxt, "4", f6="~", w="0.5"), *turn_bodies("c")[d])
    for other in ("blaze", "fern", "stone"):
        tm, tg, _f = SEEDS[other]
        rule(head(hg, "T", "C", MUT_FORE, f6="~", f7="o", w=EPS_W),
             *exp_bodies("c", "%", tm, tg)[d])

# --- stone: slow creep, blaze-proof by omission ----------------------
sm, sg, sfore = SEEDS["stone"]
for body in exp_bodies(sg, "~", sm, sg).values():
    rule(head(sm, "T", sm, sfore, w="0.05"), *body)
for other in ("blaze", "fern", "drift"):
    tm, tg, _f = SEEDS[other]
    for body in exp_bodies(sg, "~", tm, tg).values():
        rule(head(sm, "T", tm, MUT_FORE, w=EPS_W), *body)

# --- wounds ----------------------------------------------------------
for mg in ("R", "F", "C", "S", "^", ">", "v", "<", "o", ","):
    rule(head(mg, "p", "~", "7"), "@@@")
for lg in ("a", "b", "c", "d"):
    rule(head(lg, "q", "~", "7"), "@@@")

# --- plankton: wander cell-wise, sometimes leave a pellet ------------
PLK = {
    "E": exp_bodies(" ", "~", ",", " ")["E"],
    "W": exp_bodies(" ", "~", ",", " ")["W"],
    "N": ["~ ,", "@@@"],
    "S": ["@@@", "~ ,"],
}
for body in PLK.values():
    rule(head(",", "e", "~", "7"), *body)
    rule(head(",", "e", "o", "6", w="0.12"), *body)

# --- the crosshair ---------------------------------------------------
rule(head("+", "d", "$", "7"), "@@@ +")
rule(head("+", "a", "$", "7"), *exp_bodies(" ", " ", "+", " ")["W"])
rule(head("+", "w", "$", "7"), "@", "@", "+", "@")
rule(head("+", "s", "$", "7"), "@", "@", "@", "+")
rule(head("+", "x", "+", "7"), "@@@ ~~")
rule(head("+", "f", "+", "6"), "@ ~@@ o")
for name, key in (("blaze", "1"), ("fern", "2"), ("drift", "3"),
                  ("stone", "4")):
    tm, tg, fore = SEEDS[name]
    rule(head("+", key, "+", fore), f"@@@ {tm}{tg}")
rule(head("+", "r", "+", "7", snd="X"), "@@@")

OUT.parent.mkdir(exist_ok=True)
OUT.write_text("\n".join(L) + "\n")
n_rules = sum(1 for x in L if x.startswith("="))
print(f"wrote {OUT} ({n_rules} rules)")
