#!/usr/bin/env python3
"""Generate garden.cfg — the garden MVP: three species differing ONLY
in learning capability compete for ground in a toroidal seasonal
world. Reward is metabolic: a correct-arm attempt writes an offspring
into adjacent ground (and, for learners, deposits the arm token in
the same rewrite); a wrong-arm attempt is a wasted event (self
rewrite) — opportunity cost is automatic in a jump chain. Rent kills;
selection = competition for vacancies. Score tallies births only
(telemetry; nothing reads it).

Species:
  n  white   non-learner (random policy, base attempts only)
  i  yellow  linear reward-inaction (tokens ⠃/⠘: deposit+catalysis+decay)
  p  cyan    linear reward-penalty  (tokens ⠇/⠸: i + confiscation)
Token mnemonic: left dots = arm x, right dots = arm y; dot count =
species sophistication. Arms are seasons' payees (x pays under 'a',
y under 'b'); arms are symmetric WITHIN each species, so the only
difference between species is the learning machinery.

Uniform geometry: every attempt (any species, any arm) requires the
east ground pair; confiscation is its own geometry (token east).
Coverage: seeds anchor ground, rent anchors species, decay anchors
tokens — no state freezes.

Env: W (base attempt), C (catalytic), M (rent), D (decay),
SEED (immigration), PUN, OUT.
"""
import os
from pathlib import Path

NEIGH = {"n": ["i"], "i": ["n", "p"], "p": ["i"]}


def birth_rules(head_fn, body, w, mut):
    """Emit a birth rule plus mutant twins. The offspring glyph is the
    last char of the core line (the line containing the @ anchors)."""
    ci = next(i for i, l in enumerate(body) if "@" in l)
    child = body[ci][-1]
    out = []
    if mut > 0:
        self_w = w * (1 - mut / 2 * len(NEIGH[child]))
        out.append((head_fn(child, self_w), body))
        for nb in NEIGH[child]:
            mb = list(body)
            mb[ci] = mb[ci][:-1] + nb
            out.append((head_fn(nb, w * mut / 2), mb))
    else:
        out.append((head_fn(child, w), body))
    return out

W = float(os.environ.get("W", "0.2"))
C = float(os.environ.get("C", "1"))
M = float(os.environ.get("M", "0.02"))
D = float(os.environ.get("D", "0.03"))
SEED = float(os.environ.get("SEED", "0.005"))
PUN = float(os.environ.get("PUN", "1"))
TOX = float(os.environ.get("TOX", "0"))
MUT = float(os.environ.get("MUT", "0"))
START = os.environ.get("START", "all")
OUT = os.environ.get("OUT", "garden.cfg")

SPECIES = {
    "n": ("7", None),
    "i": ("3", {"x": "⠃", "y": "⠘"}),
    "p": ("6", {"x": "⠇", "y": "⠸"}),
}
SEASONS = {"a": "x", "b": "y"}
L = []
A = L.append


def g(v):
    return f"{v:g}"


A(f"#! {Path(OUT).stem}  births={{score}} steps={{steps}}")
A("# Generated by gen_garden.py -- do not edit by hand.")
A("#help garden: n white random, i yellow learns, p cyan learns+punishes")
A("#threads 1")
A("#control q quit")
A("#timing a 0")
A("")
A("^.**")
for s in SPECIES:
    if START != "all" and s not in START:
        continue
    for _ in range(12 if START != "all" else 4):
        A(f"^{s}XX")
A("")

for s, (fg, toks) in SPECIES.items():
    A(f"# --- species {s} ---")
    A("# attempts: correct arm births east (pair geometry), wrong arm")
    A("# is a wasted event; learners deposit the arm token with the birth")
    for season, paid_arm in SEASONS.items():
        dep = toks[paid_arm] if toks else ""
        # base correct: west ground takes the deposit, east the child
        core = f".@.@{dep}@{s}" if toks else f".@.@@{s}"
        for head, body in birth_rules(
                lambda ch, w2: f"=={s}{season}{s}{fg}0   1 {g(w2)}",
                [core], W, MUT):
            A(head)
            L.extend(body)
        A(f"=={s}{season}{s}{fg}0   0 {g(W)}")
        A(".@.@@")
        if TOX > 0:
            A(f"=={s}{season}.00   0 {g(W * TOX)}")
            A(".@.@@")
        if toks:
            for arm, tok in toks.items():
                correct = arm == paid_arm
                score = 1 if correct else 0
                if correct:
                    # W-token: the read slot IS the deposit slot -> no
                    # new deposit; N/S-token: deposit west as usual
                    variants = ([f"{tok}@.@@{s}"],
                                [" " + tok, f".@.@{dep}@{s}"],
                                [f".@.@{dep}@{s}", " " + tok])
                else:
                    variants = ([f"{tok}@.@@"],
                                [" " + tok, ".@.@@"],
                                [".@.@@", " " + tok])
                for body in variants:
                    if correct and MUT > 0:
                        for head, mb in birth_rules(
                                lambda ch, w2:
                                f"=={s}{season}{s}{fg}0   1 {g(w2)}",
                                list(body), C, MUT):
                            A(head)
                            L.extend(mb)
                    else:
                        A(f"=={s}{season}{s}{fg}0   {score} {g(C)}")
                        L.extend(body)
                if not correct and TOX > 0:
                    for body in ([f"{tok}@.@@"],
                                 [" " + tok, ".@.@@"],
                                 [".@.@@", " " + tok]):
                        A(f"=={s}{season}.00   0 {g(C * TOX)}")
                        L.extend(body)
            if s == "p":
                wrong = toks[{"a": "y", "b": "x"}[season]]
                A("# confiscation: a failed advised attempt eats its adviser")
                A(f"=={s}{season}{s}{fg}0   0 {g(PUN)}")
                A(f"{wrong}@@.@")
    A("# rent")
    for season in SEASONS:
        A(f"=={s}{season}.00   0 {g(M)}")
        A("@@@")
    A("# immigration keeps the species reachable (shares, not fixation)")
    for season in SEASONS:
        A(f"==.{season}{s}{fg}0   0 {g(SEED)}")
        A("@@@")
    if toks:
        A("# forgetting")
        for arm, tok in toks.items():
            for season in SEASONS:
                A(f"=={tok}{season}.00   0 {g(D)}")
                A("@@@")
    A("")

A("# watcher quit carrier")
A("=q.q.")
A("@@@")

out = Path(__file__).parent / OUT
out.write_text("\n".join(L) + "\n")
n = sum(1 for l in L if l.startswith("="))
print(f"wrote {out} ({n} rule headers, W={W} C={C} M={M} D={D} "
      f"SEED={SEED} PUN={PUN} TOX={TOX} MUT={MUT} START={START})")
