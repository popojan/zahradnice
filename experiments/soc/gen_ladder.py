#!/usr/bin/env python3
"""Generate forest-ladder.cfg — route-3 heritable trait ladder.

Extension of forest-evo.cfg from 2 species to a 5-rung quantitative
trait: rung 1 grows fast and burns hot, rung 5 grows slowly, resists
fire, and pays mortality rent (competition-colonization trade-off).
Vegetative growth is the heritable channel: offspring is the parent's
rung with prob 1-MUT, an adjacent rung with prob MUT/2 each (edges
reflect the missing mass into self so total growth rate is
position-independent). Selection acting on state can now move the
population's mean trait along the ladder — the question is whether it
tracks the lightning regime (environment = input mix of 'l' among 'T',
per forest-evo lesson 2: weights cannot make events rare at
saturation).

Scores: seed/growth +1, mortality/burnout -1, lightning/transmission 0
(plant->fire is net zero), so {score} == plants + burning cells.

Instrumentation: every rule is uniquely identified in the trace by its
source line; ladder_stats.py classifies rules by re-parsing this file.
"""
import os
from pathlib import Path

RUNGS = "12345"
FIRE_W = {"1": 4, "2": 2, "3": 1, "4": 0.5, "5": 0.25}   # vs burnout 1
GROW_W = {"1": 6, "2": 3.8, "3": 2.4, "4": 1.6, "5": 1}
MORT_W = {"1": 0, "2": 0.0025, "3": 0.005, "4": 0.0075, "5": 0.01}
FG = {"1": "2", "2": "3", "3": "7", "4": "5", "5": "6"}  # green..cyan
MUT = float(os.environ.get("MUT", "0.1"))
SEED_W = float(os.environ.get("SEED_W", "0.008"))
OUT = os.environ.get("OUT", "forest-ladder.cfg")

L = []
A = L.append


def g(x):
    return f"{x:g}"


A("#! forest-ladder  pop={score} steps={steps}")
A("# Generated by gen_ladder.py -- do not edit by hand.")
A("#help ladder: 1 fast/hot .. 5 slow/resistant | l lightning | q quit")
A("#threads 1")
A("#control q quit")
A("#timing l 3000")
A("#timing T 0")
A("")
A("# ground fill + a symmetric pinch of every rung")
A("^.**")
for k in RUNGS:
    A(f"^{k}XX")
    A(f"^{k}XX")
A("")

A("# seed rain: uniform tiny immigration keeps every rung reachable")
for k in RUNGS:
    A(f"==.T{k}{FG[k]}0   1 {g(SEED_W)}")
    A("@@@")
A("")

A("# vegetative growth with mutation: parent k begets k (0.9), k+-1")
A("# (0.05 each); edge rungs reflect into self. Heads sharing a body")
A("# differ only in offspring glyph and weight.")
for p in RUNGS:
    kids = {p: 1 - MUT}
    for q in (chr(ord(p) - 1), chr(ord(p) + 1)):
        if q in RUNGS:
            kids[q] = MUT / 2
        else:
            kids[p] += MUT / 2
    heads = [f"==.T{o}{FG[o]}0   1 {g(GROW_W[p] * w)}"
             for o, w in sorted(kids.items())]
    for body in ([f"@{p}@@"], [f"{p}@@@"],
                 [p, "@", "@", "@"], ["@", p, "@", "@"]):
        L.extend(heads)
        L.extend(body)
A("")

A("# lightning on its own trigger; ignition is species-equal")
for k in RUNGS:
    A(f"=={k}lA13   0 1")
    A("@@@")
A("")

A("# fire transmission: weight = victim's flammability")
for v in RUNGS:
    w = g(FIRE_W[v])
    for body in ([f"@{v}@@A"], [f"{v}@@A@"],
                 [v, "@", "@", "A", "@"], ["@", v, "@", "@", "A"]):
        A(f"==ATA13   0 {w}")
        L.extend(body)
A("")

A("# rent: natural mortality rises toward the fire-resistant end")
for k in RUNGS:
    if MORT_W[k] > 0:
        A(f"=={k}T.00   -1 {g(MORT_W[k])}")
        A("@@@")
A("")

A("# burnout")
A("==AT.00   -1 1")
A("@@@")
A("")
A("# watcher quit carrier")
A("=q.q.")
A("@@@")

out = Path(__file__).parent / OUT
out.write_text("\n".join(L) + "\n")
n = sum(1 for l in L if l.startswith("="))
print(f"wrote {out} ({n} rule headers)")
