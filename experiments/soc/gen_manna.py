#!/usr/bin/env python3
"""Generate manna.cfg and manna-watch.cfg -- one sandpile, two framings.

v3: both files come from here. They share every toppling and dissipation rule,
which is the whole content of the model; they differ in how the run is started,
how it is driven, and what the screen is allowed to say about it. Keeping them
in one generator is what makes "the watch copy is the same sandpile" a fact
about the source rather than a claim in a comment.

  manna.cfg        the measured one. Empty field, drive on its own 1500 ms
                   timing, toppling relaxed at loop speed, no colour.
                   results.md's numbers come from this file.
  manna-watch.cfg  the watchable one. Warm start at the stationary density, a
                   self-pacing drive that waits for the avalanche, TICK ms per
                   applied rule, and colour that is a function of state.

The two differ inside the shared rules in exactly two positions, both of which
the engine ignores when matching:

  fore(dst)  header field 4, the colour of the site the rule rewrites. manna
             leaves it 7; manna-watch names the height's colour.
  land(k1)   what the *receiver* cell is written as. manna writes the height.
             manna-watch writes a landing marker that an F rule collapses back
             to that height, because a rule has one colour pair and writes two
             cells of differing height -- see manna-watch.cfg's header.

v2 (unchanged here): proper Manna toppling. An active site (height >= 2) sheds
TWO grains, one at a time, via owe-states u/v/w ("owes one more grain", holding
0/1/2 grains): 2->u->0, 3->v->1, 4->w->2. Receivers are digits 0..3 (->+1) and
owe-states u,v (->v,w); height-4 and owe-w receivers have no rule, so that
direction is simply unavailable (rare).

v1 shed a single grain (2->1), so no interior site could ever empty: density
locked at 1.0 and each "avalanche" was one excess grain random-walking to the
wall (hump-shaped first-passage sizes) -- false negative #4, caught by the
density check (grains == sites) and the non-power-law shape. The zeros created
by double-shedding are exactly where Manna's critical density < 1 comes from.

Bodies whose first column would start with '#' are uniformly indented one
space (GRAMMAR.md body-line escape).
"""
from pathlib import Path

SHED = {"2": "u", "3": "v", "4": "w", "u": "0", "v": "1", "w": "2"}
RECV = {"0": "1", "1": "2", "2": "3", "3": "4", "u": "v", "v": "w"}


def body(L, lines):
    if any(l and l[0] in "#^=" for l in lines):
        lines = [" " + l for l in lines]
    L.extend(lines)


def rules(fore, land):
    """The model. Identical for both files but for fore() and land()."""
    L = ["# toppling: shed one grain to a random neighbour"]
    for src, dst in SHED.items():
        head = f"=={src}T{dst}{fore[dst]}8"
        for k, k1 in RECV.items():
            for shape in ([f"@{k}@@{land[k1]}"],
                          [f"{k}@@{land[k1]}@"],
                          [k, "@", "@", land[k1], "@"],
                          ["@", k, "@", "@", land[k1]]):
                L.append(head)
                body(L, shape)

    L.append("")
    L.append("# dissipation: grains shed into a wall leave the system")
    for src, dst in SHED.items():
        head = f"=={src}T{dst}{fore[dst]}8   -1 1"
        for shape in (["@#@@"], ["#@@@"],
                      ["#", "@", "@", "@"], ["@", "#", "@", "@"]):
            L.append(head)
            body(L, shape)
    return "\n".join(L) + "\n"


# manna: no colour (field 4 stays 7), the receiver is written as its height.
PLAIN_FORE = {c: "7" for c in "01234uvw"}
PLAIN_LAND = {c: c for c in RECV.values()}

# manna-watch: the colour of the state the rule leaves at the site, and the
# landing marker standing in for the receiver's height. 1 takes its colour
# from TRAIL (alias L) so the avalanche footprint can be switched on.
WATCH_FORE = {"0": "E", "1": "L", "2": "A", "3": "H", "4": "X",
              "u": "M", "v": "M", "w": "M"}
WATCH_LAND = {"1": "h", "2": "i", "3": "j", "4": "k", "v": "y", "w": "z"}

PLAIN_HEAD = """#! manna  grains={score} steps={steps}  | {help}
# Generated by gen_manna.py -- do not edit by hand.
#threads 1
#timing T 0
#timing d 1500
#help sandpile: grains drop, piles topple | q back
#control q return

# field of empty sites framed by absorbing walls (fill marker)
^0**
^#u*
^#l*
^#*l
^#*r

# drive: one grain onto a random quiet site
==0d178   1 1
@@@
==1d278   1 1
@@@

# carrier for the quit control
=q0q0
@@@

"""

PLAIN_TAIL = """# q returns to the caller. Anchored on a character measured to be on
# screen at every sampled step of a long run -- a head-state anchor
# would make the key work only sometimes.
=q#q#
 @@@
"""

WATCH_HEAD = """#! manna-watch  grains={score} steps={steps}  | {help}
# Manna sandpile, arranged to be *watched* rather than measured. A copy of
# manna.cfg (generated by gen_manna.py); regenerating that file does not
# regenerate this one. The toppling and dissipation rules below keep manna.cfg's
# geometry exactly -- only the start, the drive and the colouring differ, and
# results.md's numbers come from manna.cfg, which is untouched.
#
# Two problems with watching the original:
#  * it fills by driving, so reaching the critical density costs ~0.7*L^2
#    drives -- ~300 at L=16 (measured), ~9000 on a full screen, and at one
#    grain per 1.5 s that is hours before anything interesting happens;
#  * `#timing T 0` relaxes each avalanche at loop speed, so the avalanche --
#    the thing worth seeing -- is a flicker.
#
# Warm start. The field is seeded with 's' and each site resolves to occupied
# or empty at FILL_ON:FILL_OFF = 7:3, the stationary density: the pile begins
# *at* the attractor instead of crawling toward it. No site starts above the
# toppling threshold, so the state is stable and nothing resolves until the
# first grain lands (measured first avalanches: 110, 0, 90, 12, 2, 0 -- ordinary
# sizes, no initial cascade). The occupied branch scores +1, so {score} still
# counts grains. This is only legitimate because the sandpile passed the
# L-scaling test: the attractor does not remember how it was reached.
#
# The fill runs on its own immediate trigger F, so it completes in one event
# per site rather than one per TICK; once no 's' is left those two rules have
# no anchor and F disarms itself.
#
# Self-pacing drive. The drive moved onto T with a negligible weight, so while
# the pile is active toppling outweighs it and it never intrudes -- and the
# moment the pile settles it is the only applicable rule and fires on the next
# tick ("a tiny weight does not make an event rare when it is the only rule
# that matches"). The grain waits for the avalanche at any speed and any field
# size, which no fixed #timing interval can do.
#
# Colour, and the landing markers that make it possible. The obvious plan --
# one colour per height -- does not fit the engine: it has one foreground pair
# per rule *application*, and a toppling rule writes two cells, the site and
# the neighbour it sheds to, whose heights differ. Colouring by the rule
# therefore stains the receiver with the site's colour, and the stain is
# permanent: nothing repaints a quiescent cell, and a repaint rule (1 -> 1)
# would be applicable forever, so its immediate trigger could never disarm and
# the program would spin a core.
#
# So the receiver is not written as its new height at all. It is written as a
# landing marker (h i j k y z, one per RECV target 1 2 3 4 v w) and an F rule
# collapses the marker to the height it stands for. Every write is then a
# single-state write, and colour is exactly a function of state:
#
#   0      E  dim blue      empty
#   1      G  dim cyan      one grain, at rest
#   2 3 4  A H X  yellow, bright yellow, red    over threshold: will topple
#   u v w  M  magenta       owes a grain: mid-transfer, the avalanche front
#   #      W  blue          the absorbing wall
#
# Nothing on screen is stale and nothing is white. Cool is the pile at rest --
# and because 0 and 1 differ, the cool speckle *is* the occupancy field, the
# order parameter. Every warm cell is one that moves on the next tick.
#
# The markers cost no dynamics. F is immediate and interval timings are checked
# first, so the F event after a toppling collapses the marker before T comes
# round again -- a marker is never on screen when a rule reads it, and the
# reachable states are manna.cfg's (checked: field mass == {score}). The T
# headers on the marker rules are the safety net for the one case F can miss (a
# key repeating through a whole tick); they outweigh every toppling rule, so the
# marker is cleared and the toppling waits a tick. What does change is the RNG
# stream: each toppling now spends an extra F event, so a seed no longer
# replays manna.cfg's trajectory. Same distribution, different path -- the
# right side of the trade for the watching copy.
#
# TRAIL is the one history channel, off by default. --param TRAIL=3 paints
# yellow every grain an avalanche put down or left behind (the h landing and
# the v settle, both of which end at height 1), so the pile shows where
# avalanches have been rather than what it is doing now. It fills in and then
# saturates -- 8% at 0.3 min, 25% at 1.3, 50% at 4, then ~56% for good --
# because at stationarity the avalanche support really is the whole pile.
# Watching it spread is the point; leaving it on past that just recolours the
# 1s. It is also the one setting that breaks "warm == moves next tick".
#
# Slow motion: TICK ms per applied rule. Raise it to see individual topplings,
# lower it for a livelier pile:  --param TICK=150
#parameter TRAIL 6,DIM
#parameter TICK 40
#parameter DRIVE 0.00000001
#parameter FILL_ON 7
#parameter FILL_OFF 3
#threads 1
#timing T {TICK}
#timing F 0
#color E 4,DIM
#color G 6,DIM
#color A 3
#color H 3,BOLD
#color X 1
#color M 5
#color W 4
#color L {TRAIL}
#help sandpile: grains drop, piles topple | q back
#control q return

# field of seed sites framed by absorbing walls (fill marker). The walls are
# seeded as 'b' and painted '#' by a rule below, because a '^' starting symbol
# paints in the terminal default and cannot carry a colour.
^s**
^bu*
^bl*
^b*l
^b*r

# warm start: each seeded site becomes occupied or empty at the stationary
# density, at F speed. Self-terminating.
==sF1G8   1 {FILL_ON}
@@@
==sF0E8   0 {FILL_OFF}
@@@

# the frame, in its own colour. Self-terminating like the fill above.
==bF#W8
@@@

# landing markers: a shed grain arrives as h/i/j/k/y/z and the next F event
# collapses it to the height it stands for, in that height's colour. See the
# header for why the receiver cannot simply be written as its height, and why
# the h rule takes its colour from TRAIL rather than from G.
==hF1L8
==hT1L8   0 1000
@@@
==iF2A8
==iT2A8   0 1000
@@@
==jF3H8
==jT3H8   0 1000
@@@
==kF4X8
==kT4X8   0 1000
@@@
==yFvM8
==yTvM8   0 1000
@@@
==zFwM8
==zTwM8   0 1000
@@@

# drive: one grain onto a random quiet site. Shares the toppling trigger, so
# it fires only when nothing is toppling.
==0T1G8   1 {DRIVE}
@@@
==1T2A8   1 {DRIVE}
@@@

# carrier for the quit control
=q0q0E8
@@@

"""

WATCH_TAIL = """# q returns to the caller. Anchored on a character measured to be on
# screen at every sampled step of a long run -- a head-state anchor
# would make the key work only sometimes.
=q#q#W8
 @@@
"""

VARIANTS = [
    ("manna.cfg", PLAIN_HEAD, PLAIN_TAIL, PLAIN_FORE, PLAIN_LAND),
    ("manna-watch.cfg", WATCH_HEAD, WATCH_TAIL, WATCH_FORE, WATCH_LAND),
]

for fname, head, tail, fore, land in VARIANTS:
    out = Path(__file__).parent / fname
    text = head + rules(fore, land) + "\n" + tail
    out.write_text(text)
    n = sum(1 for l in text.split("\n") if l.startswith("="))
    print(f"wrote {out} ({n} rule headers)")
