#!/usr/bin/env python3
"""Generate forest-bank.cfg — route-3 milestone 3: the seed-bank
integrator (superset of gen_ladder.py's trait ladder).

The bank is matter, the rules stay immutable: dormant seeds are
first-class field cells using Braille glyphs (dot count = rung,
U+2801..U+281F). Fire transmission and vegetative growth have no
rules touching them — protection by omission is physics. Three bank
rule families per rung k:
  deposit:    '.' next to standing k -> seed(k), weight DEP*w_k
              (true-breeding copy; mutation stays in growth)
  germinate:  seed(k) -> standing k, in place, weight G
  decay:      seed(k) -> '.', weight D
Retention: a seed's per-event hazard is (G+D)/applicable-mass, so its
lifetime is set by a weight ratio against the ambient churn — the
clock. To guarantee a clock exists even at all-1 saturation, rung 1
pays a small mortality (M1) here, unlike forest-ladder.cfg (whose
all-1 state froze). DEP=0 omits the bank entirely (control with
identical vegetation physics) — weight 0 would clamp to 1, so the
rules must be absent, not zero-weighted.

Scores: deposit +1, decay -1, germinate 0 (seed->plant is net zero),
so {score} == standing + burning + banked.

Env: MUT, SEED_W, M1, DEP, G, D, OUT.
"""
import os
from pathlib import Path

RUNGS = "12345"
SEED = {k: chr(0x2800 + 2 ** int(k) - 1) for k in RUNGS}  # dots = rung
FIRE_W = {"1": 4, "2": 2, "3": 1, "4": 0.5, "5": 0.25}   # vs burnout 1
GROW_W = {"1": 6, "2": 3.8, "3": 2.4, "4": 1.6, "5": 1}
FG = {"1": "2", "2": "3", "3": "7", "4": "5", "5": "6"}  # green..cyan
MUT = float(os.environ.get("MUT", "0.1"))
SEED_W = float(os.environ.get("SEED_W", "0.008"))
M1 = float(os.environ.get("M1", "0.001"))
DEP = float(os.environ.get("DEP", "0.02"))
G = float(os.environ.get("G", "0.0002"))
D = float(os.environ.get("D", "0.00005"))
CAT = float(os.environ.get("CAT", "0"))
OUT = os.environ.get("OUT", "forest-bank.cfg")
MORT_W = {"1": M1, "2": 0.0025, "3": 0.005, "4": 0.0075, "5": 0.01}

L = []
A = L.append


def g(x):
    return f"{x:g}"


A(f"#! {Path(OUT).stem}  pop={{score}} steps={{steps}}")
A("# Generated by gen_bank.py -- do not edit by hand.")
A("#help bank: 1 fast/hot .. 5 slow/resistant, braille = dormant seeds"
  " | l lightning | q quit")
A("#threads 1")
A("#control q quit")
A("#timing l 3000")
A("#timing T 0")
A("")
A("# ground fill + a symmetric pinch of every rung")
A("^.**")
for k in RUNGS:
    A(f"^{k}XX")
    A(f"^{k}XX")
A("")

A("# seed rain: uniform tiny immigration keeps every rung reachable")
for k in RUNGS:
    A(f"==.T{k}{FG[k]}0   1 {g(SEED_W)}")
    A("@@@")
A("")

A("# vegetative growth with mutation: parent k begets k (0.9), k+-1")
A("# (0.05 each); edge rungs reflect into self.")
for p in RUNGS:
    kids = {p: 1 - MUT}
    for q in (chr(ord(p) - 1), chr(ord(p) + 1)):
        if q in RUNGS:
            kids[q] = MUT / 2
        else:
            kids[p] += MUT / 2
    heads = [f"==.T{o}{FG[o]}0   1 {g(GROW_W[p] * w)}"
             for o, w in sorted(kids.items())]
    for body in ([f"@{p}@@"], [f"{p}@@@"],
                 [p, "@", "@", "@"], ["@", p, "@", "@"]):
        L.extend(heads)
        L.extend(body)
A("")

if DEP > 0:
    A("# bank deposit: reproduction sometimes drops a dormant seed")
    A("# (true-breeding copy of the parent) instead of a sprout")
    for p in RUNGS:
        head = f"==.T{SEED[p]}{FG[p]}0   1 {g(DEP * GROW_W[p])}"
        for body in ([f"@{p}@@"], [f"{p}@@@"],
                     [p, "@", "@", "@"], ["@", p, "@", "@"]):
            A(head)
            L.extend(body)
    A("")
    if CAT > 0:
        A("# catalytic readout: a seed TEMPLATES its rung into adjacent")
        A("# bare ground without being consumed (read-by-template, i.e.")
        A("# transcription; germination below is read-by-consumption).")
        A("# Influence now scales with CAT while retention stays G+D.")
        for k in RUNGS:
            s = SEED[k]
            head = f"=={s}T{s}{FG[k]}0   1 {g(CAT)}"
            for body in ([f"@.@@{k}"], [f".@@{k}@"],
                         ["@", ".", "@", "@", k], [".", "@", "@", k, "@"]):
                A(head)
                L.extend(body)
        A("")
    A("# germination: a seed wakes as its rung, in place")
    for k in RUNGS:
        A(f"=={SEED[k]}T{k}{FG[k]}0   0 {g(G)}")
        A("@@@")
    A("")
    A("# seed decay: the bank leaks")
    for k in RUNGS:
        A(f"=={SEED[k]}T.00   -1 {g(D)}")
        A("@@@")
    A("")

A("# lightning on its own trigger; ignition is species-equal")
for k in RUNGS:
    A(f"=={k}lA13   0 1")
    A("@@@")
A("")

A("# fire transmission: weight = victim's flammability; seeds fireproof")
for v in RUNGS:
    w = g(FIRE_W[v])
    for body in ([f"@{v}@@A"], [f"{v}@@A@"],
                 [v, "@", "@", "A", "@"], ["@", v, "@", "@", "A"]):
        A(f"==ATA13   0 {w}")
        L.extend(body)
A("")

A("# rent: every rung pays; rung 1 pays least but is never a frozen")
A("# absorbing state (the clock must tick)")
for k in RUNGS:
    if MORT_W[k] > 0:
        A(f"=={k}T.00   -1 {g(MORT_W[k])}")
        A("@@@")
A("")

A("# burnout")
A("==AT.00   -1 1")
A("@@@")
A("")
A("# watcher quit carrier")
A("=q.q.")
A("@@@")

out = Path(__file__).parent / OUT
out.write_text("\n".join(L) + "\n")
n = sum(1 for l in L if l.startswith("="))
print(f"wrote {out} ({n} rule headers, DEP={DEP} G={G} D={D} M1={M1})")
