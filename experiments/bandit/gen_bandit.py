#!/usr/bin/env python3
"""Generate bandit.cfg — the route-3 summit experiment
(research-rl-ai.md S14): reward-following with reversal, no optimizer.

World: ground '.' blooms flowers x/y (the two arms). Season is TIME,
not space — the trigger char ('a' or 'b') carried by the input stream
IS the environment: under 'a' an x-bloom pays +1, under 'b' a y-bloom
does. The paying rule deposits the arm's token (Braille) into the
adjacent ground cell IN THE SAME REWRITE — action, reward and weight
update are one rule application. Tokens catalyze their own arm's
blooming (policy = token mass, mass-action) and decay slowly
(forgetting). The arms are EXACTLY symmetric — same geometry, same
weights, no mortality channel at all — so any policy shift is pure
reward-following, not selection.

Every bloom rule requires an east ground pair (uniform geometry across
arms/seasons/variants, so applicability never biases the readout);
catalytic rules read the token from W/N/S and deposit east.

LEARN=0 strips the deposit cells (score kept): the no-learning
control — identical physics, reward disconnected from state.

Env: B (base bloom), C (catalytic bloom), W (wilt), D (token decay),
LEARN, OUT.
"""
import os
from pathlib import Path

B = float(os.environ.get("B", "0.05"))
C = float(os.environ.get("C", "0.5"))
W = float(os.environ.get("W", "1"))
D = float(os.environ.get("D", "0.002"))
PUN = float(os.environ.get("PUN", "0"))
LEARN = os.environ.get("LEARN", "1") != "0"
OUT = os.environ.get("OUT", "bandit.cfg")

ARMS = {"x": ("⠋", "2"), "y": ("⠙", "5")}  # glyph->(token,fg)
SEASONS = {"a": "x", "b": "y"}  # which arm pays under which trigger

L = []
A = L.append


def g(v):
    return f"{v:g}"


A(f"#! {Path(OUT).stem}  reward={{score}} steps={{steps}}")
A("# Generated by gen_bandit.py -- do not edit by hand.")
A("#help bandit: arms x/y bloom, tokens remember | a/b = season | q quit")
A("#threads 1")
A("#control q quit")
A("#timing a 0")
A("")
A("^.**")
A("")

A("# blooms: base rate (exploration floor) + token-catalyzed rate")
A("# (the policy). Paying combinations score +1 and deposit the token")
A("# east in the same rewrite; free combinations are identical minus")
A("# score and deposit. All variants require the east ground pair.")
for season, paid_arm in SEASONS.items():
    for arm, (tok, fg) in ARMS.items():
        pays = arm == paid_arm
        score = 1 if pays else 0
        dep = tok if (pays and LEARN) else ""
        A(f"==.{season}{arm}{fg}0   {score} {g(B)}")
        A(f"@.@@{dep}")
        cat_bodies = (
            [f"{tok}@.@@{dep}"],
            [tok, f"@.@@{dep}"],
            [f"@.@@{dep}", tok],
        )
        for body in cat_bodies:
            A(f"==.{season}{arm}{fg}0   {score} {g(C)}")
            L.extend(body)
A("")

if PUN > 0:
    A("# MENACE's other half: confiscation. An unpaid attempt advised")
    A("# by an east token blooms (the failed try) and eats the adviser")
    A("# in the same rewrite -- outcome-coupled punishment, the east")
    A("# lane as ledger: deposit writes it, confiscation erases it.")
    for season, paid_arm in SEASONS.items():
        for arm, (tok, fg) in ARMS.items():
            if arm != paid_arm:
                A(f"==.{season}{arm}{fg}0   0 {g(PUN)}")
                A(f"@{tok}@@.")
    A("")

A("# wilt: flowers clear, the arm can be pulled again")
for arm in ARMS:
    for season in SEASONS:
        A(f"=={arm}{season}.70   0 {g(W)}")
        A("@@@")
A("")

A("# forgetting: tokens decay")
for arm, (tok, fg) in ARMS.items():
    for season in SEASONS:
        A(f"=={tok}{season}.70   0 {g(D)}")
        A("@@@")
A("")

A("# watcher quit carrier")
A("=q.q.")
A("@@@")

out = Path(__file__).parent / OUT
out.write_text("\n".join(L) + "\n")
n = sum(1 for l in L if l.startswith("="))
print(f"wrote {out} ({n} rule headers, B={B} C={C} W={W} D={D} "
      f"LEARN={int(LEARN)} PUN={PUN})")
