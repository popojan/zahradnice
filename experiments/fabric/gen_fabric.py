#!/usr/bin/env python3
"""gen_fabric.py -- R0.1: a perceptron in glyphs (backlog/fabric/01-ladder.md).

Layout (screen rows 1..3, cols 0..10; row 0 is the status line):

  row 1:  #  _ _ _ _ _ _ _ _  y  |     inputs (typed o/x by a head >), bias y, end |
  row 2:     s s s s s s s s  s        synapse glyphs: . = 0, A..H = +1..+8, a..h = -1..-8
  row 3:                         N     the neuron: a drift-diffusion counter glyph

Triggers (all keys, no timing):
  b        build the layout (once)
  0 / 1    the head > types o / x into the next input cell and advances
  i        inference: the counter steps +1 with mass sum(|w| over active + inputs),
           -1 with mass sum(|w| over active - inputs) + THETA; at +K it becomes 1,
           at -K it becomes 0 (gambler's ruin => sigmoid of gain K in log-odds)
  p / n    teacher says the label is 1 / 0: the neuron is marked + (correct, +1
           score), - (missed) or / (false alarm); then every active synapse steps
           toward the label once (its input is consumed x -> X, y -> Y)
  c        clear activities for the next sample (synapses untouched), replant head

Parameters: K counter half-range, N magnitude cap, THETA base down-mass, NIN inputs.
"""
import os, sys

K = int(os.environ.get("K", 16))
N = int(os.environ.get("N", 8))
THETA = float(os.environ.get("THETA", 4))
NIN = int(os.environ.get("NIN", 8))
OUT = os.environ.get("OUT", "fabric-r01.cfg")
BIAS = int(os.environ.get("BIAS", 1))

POS = "ABCDEFGHIJKLMNOP"[:N]       # +1..+N
NEG = "abcdefghijklmnop"[:N]       # -1..-N
ZERO = "."

def wglyph(w):
    if w == 0: return ZERO
    return POS[w - 1] if w > 0 else NEG[-w - 1]

def state(j):                      # counter state j in [-K..K] -> a Braille glyph
    return chr(0x2800 + 0x40 + j)  # U+2830..U+2860 for K=16: never blank U+2800

NCOL = NIN + 1 if BIAS else NIN    # bias input sits at column NIN+1
OUTC = NCOL + 1                    # neuron column (under the terminator |)
INCOLS = list(range(1, NIN + 1))
BIASC = NIN + 1

def header(lhs, trig, rhs, ctx=" ", ctxrep=" ", score=0, weight=1):
    h = "==" + lhs + trig + rhs + "78" + ctx + ctxrep
    assert len(h) == 9, h
    w = ("%g" % weight)
    return "%s %d %s" % (h, score, w)   # tail starts at column 10

def body(lhs_cells, rhs_cells):
    """lhs_cells / rhs_cells: {(dr, dc): ch} relative to the anchor, anchor excluded.
    Horizontal layout: LHS block | boundary @ | RHS block (regions split by column)."""
    lr0 = min([0] + [r for r, _ in lhs_cells]); lr1 = max([0] + [r for r, _ in lhs_cells])
    lc0 = min([0] + [c for _, c in lhs_cells]); lc1 = max([0] + [c for _, c in lhs_cells])
    rr0 = min([0] + [r for r, _ in rhs_cells]); rr1 = max([0] + [r for r, _ in rhs_cells])
    rc0 = min([0] + [c for _, c in rhs_cells]); rc1 = max([0] + [c for _, c in rhs_cells])
    W = lc1 - lc0 + 1
    R0, R1 = min(lr0, rr0), max(lr1, rr1)
    width = W + 1 + (rc1 - rc0 + 1)
    rows = [[" "] * width for _ in range(R1 - R0 + 1)]
    def put(r, c, ch):
        assert rows[r - R0][c] == " ", (r, c, ch)
        rows[r - R0][c] = ch
    put(0, -lc0, "@")                       # @1 anchor
    for (r, c), ch in lhs_cells.items(): put(r, c - lc0, ch)
    put(0, W, "@")                          # @2 boundary, on the anchor row
    base = W + 1 - rc0
    put(0, base, "@")                       # @3 rhs anchor
    for (r, c), ch in rhs_cells.items(): put(r, base + c, ch)
    lines = ["".join(row).rstrip() for row in rows]
    assert lines[0].strip(), "first body row must hold a cell"
    for ln in lines:
        assert not ln[:1] in ("#", "=", "^"), ln
    return "\n".join(lines)

out = []
def rule(h, lhs_cells, rhs_cells=None, comment=None):
    if comment: out.append("# " + comment)
    out.append(h); out.append(body(lhs_cells, rhs_cells or {}))

out.append("#! fabric R0.1 perceptron  correct={score} steps={steps}")
out.append("# Generated by gen_fabric.py K=%d N=%d THETA=%g NIN=%d BIAS=%d -- do not edit." % (K, N, THETA, NIN, BIAS))
out.append("#threads 1")
out.append("^Bul")

# build: one rule lays out the whole fabric from the builder at (1,0)
rhs = {(0, c): "_" for c in INCOLS}
if BIAS: rhs[(0, BIASC)] = "y"
rhs[(0, OUTC)] = "|"
INIT = os.environ.get("INIT", "")          # optional initial synapse glyphs, cols 1..
for c in INCOLS: rhs[(1, c)] = INIT[c - 1] if c - 1 < len(INIT) else ZERO
if BIAS: rhs[(1, BIASC)] = INIT[BIASC - 1] if BIASC - 1 < len(INIT) else ZERO
rhs[(2, OUTC)] = state(0)
rule(header("B", "b", "#"), {}, rhs, "build the layout")

# typing: head > writes o/x and advances east while east is _, else dies
for trig, ch in (("0", "o"), ("1", "x")):
    rule(header(">", trig, ch), {(0, 1): "_"}, {(0, 1): ">"}, "type %s, advance" % ch)
    rule(header(">", trig, ch, ctx="_"), {(0, 1): "!"}, {}, "type %s at the end" % ch)

# inference: the counter walks. From state j (undecided, |j| < K) to j+-1;
# from K-1 up -> 1 (fired), from -K+1 down -> 0 (refused).
def up_to(j):   return "1" if j + 1 == K else state(j + 1)
def down_to(j): return "0" if j - 1 == -K else state(j - 1)
cols = INCOLS + ([BIASC] if BIAS else [])
for j in range(-K + 1, K):
    s = state(j)
    out.append("# counter state %d" % j)
    for c in cols:
        act = "y" if c == BIASC else "x"
        for w in range(1, N + 1):
            lhs = {(-2, c - OUTC): act, (-1, c - OUTC): wglyph(w)}
            out.append(header(s, "i", up_to(j), weight=w));   out.append(body(lhs, {}))
            lhs = {(-2, c - OUTC): act, (-1, c - OUTC): wglyph(-w)}
            out.append(header(s, "i", down_to(j), weight=w)); out.append(body(lhs, {}))
    out.append(header(s, "i", down_to(j), weight=THETA)); out.append(body({}, {}))

# teacher: mark the neuron. Undecided (still a counter state) counts as refused.
rule(header("1", "p", "+", score=1), {}, {}, "correct positive")
rule(header("0", "p", "-"), {}, {}, "missed")
rule(header("0", "n", "+", score=1), {}, {}, "correct negative")
rule(header("1", "n", "/"), {}, {}, "false alarm")
for j in range(-K + 1, K):
    out.append(header(state(j), "p", "-")); out.append(body({}, {}))
    out.append(header(state(j), "n", "+", score=1)); out.append(body({}, {}))

# learning: an active synapse under a marked neuron steps once toward the label;
# the rewrite consumes the input (x->X, y->Y) so each synapse steps at most once.
out.append("# learning")
for c in cols:
    act, used = ("y", "Y") if c == BIASC else ("x", "X")
    for w in range(-N, N + 1):
        g = wglyph(w)
        up = wglyph(min(N, w + 1)); dn = wglyph(max(-N, w - 1))
        lhs = {(-1, 0): act, (1, OUTC - c): "-"}
        out.append(header(g, "p", up)); out.append(body(lhs, {(-1, 0): used}))
        lhs = {(-1, 0): act, (1, OUTC - c): "/"}
        out.append(header(g, "n", dn)); out.append(body(lhs, {(-1, 0): used}))

# clear: activities back to blank, neuron back to state 0, head replanted
out.append("# clear")
for g in "oxX": out.append(header(g, "c", "_")); out.append(body({}, {}))
if BIAS: out.append(header("Y", "c", "y")); out.append(body({}, {}))
for g in "01+-/": out.append(header(g, "c", state(0))); out.append(body({}, {}))
for j in range(-K + 1, K):
    if j != 0: out.append(header(state(j), "c", state(0))); out.append(body({}, {}))
rule(header("#", "c", "#"), {(0, 1): "_"}, {(0, 1): ">"}, "replant the head")

open(OUT, "w", encoding="utf-8").write("\n".join(out) + "\n")
nrules = sum(1 for l in out if l.startswith("="))
print("%s: %d rules" % (OUT, nrules))
