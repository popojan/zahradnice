#!/usr/bin/env python3
"""gen_tm.py -- a Tsetlin-machine-shaped fabric in glyphs, translation-invariant edition.

Every rule family reads at offsets that do not depend on the clause, so the rule
count is independent of C and each event dry-runs only the rules of the few
anchors present (the first edition paid C x per rule and C^2 per event).

Layout (row 0 = status; per clause c three rows A/B/H at 2+3c):
  row 1   : #  _ x NIN  |                       the typing head > walks here
  row A   : literal values, t/u at cols 1..8 (x_i) and 10..17 (not x_i)   [written by typing]
  row B   : clause output (1/0) at col 0, automata a..h (excluded) A..H (included), | at col 9
  row H   : feedback head row (a head glyph walks east, one automaton per event)
  last    : the readout neuron at col 0 (counter glyph; Y fired / N refused; + - / marker)

Triggers: b build | 0/1 type (writes the bit and its literals into every clause) |
i evaluate (clause 1 -> 0 if an included literal is untrue) | o readout walk |
p/n teacher (one event): mark the neuron and plant a feedback head per clause (head glyph =
feedback type x right/wrong) | f: the head reads the clause output on its first step, then walks
along the automata applying Tsetlin Type I / II feedback as step-vs-skip rule weights |
c clear (neuron, clause outputs, head replant).
Params: C N S K THETA Q NIN.
"""
import os

C = int(os.environ.get("C", 8)); N = int(os.environ.get("N", 8)); S = float(os.environ.get("S", 4))
K = int(os.environ.get("K", 8)); THETA = float(os.environ.get("THETA", 1)); Q = float(os.environ.get("Q", 0.1))
NIN = int(os.environ.get("NIN", 8)); OUT = os.environ.get("OUT", "fabric-tm.cfg")
BIG = 1e6
SEP = NIN + 1
POSK = list(range(1, NIN + 1)) + list(range(SEP + 1, SEP + 1 + NIN))
LASTK = SEP + NIN

def fresh(s):   return ("abcdefghijklmnop"[:N])[s - 1] if s <= N else ("ABCDEFGHIJKLMNOP"[:N])[s - N - 1]
def state(j):   return chr(0x2800 + 0x40 + j)
def rowA(c): return 2 + 3 * c
def rowB(c): return 3 + 3 * c
def rowH(c): return 4 + 3 * c
NROW = 2 + 3 * C
# head glyphs: planted (type, wrong) -> after reading the clause output -> walking (type, wrong, out)
PLANT = {("I", True): "{", ("I", False): "}", ("II", True): "(", ("II", False): ")"}
WALK = {("I", True, 1): "5", ("I", True, 0): "6", ("I", False, 1): "7", ("I", False, 0): "8",
        ("II", True, 1): "9", ("II", True, 0): ":", ("II", False, 1): ";", ("II", False, 0): "<"}

def header(lhs, trig, rhs, ctx=" ", ctxrep=" ", score=0, weight=1):
    h = "==" + lhs + trig + rhs + "78" + ctx + ctxrep
    assert len(h) == 9, h
    return "%s %d %s" % (h, score, "%g" % weight)

def body(lhs_cells, rhs_cells):
    lr0 = min([0] + [r for r, _ in lhs_cells]); lr1 = max([0] + [r for r, _ in lhs_cells])
    lc0 = min([0] + [c for _, c in lhs_cells]); lc1 = max([0] + [c for _, c in lhs_cells])
    rr0 = min([0] + [r for r, _ in rhs_cells]); rr1 = max([0] + [r for r, _ in rhs_cells])
    rc0 = min([0] + [c for _, c in rhs_cells]); rc1 = max([0] + [c for _, c in rhs_cells])
    W = lc1 - lc0 + 1; R0, R1 = min(lr0, rr0), max(lr1, rr1)
    width = W + 1 + (rc1 - rc0 + 1)
    rows = [[" "] * width for _ in range(R1 - R0 + 1)]
    def put(r, c, ch):
        assert rows[r - R0][c] == " ", (r, c, ch); rows[r - R0][c] = ch
    put(0, -lc0, "@")
    for (r, c), ch in lhs_cells.items(): put(r, c - lc0, ch)
    put(0, W, "@"); base = W + 1 - rc0; put(0, base, "@")
    for (r, c), ch in rhs_cells.items(): put(r, base + c, ch)
    lines = ["".join(row).rstrip() for row in rows]
    assert lines[0].strip()
    for ln in lines: assert ln[:1] not in ("#", "=", "^"), ln
    return "\n".join(lines)

out = []
def rule(h, lhs, rhs=None):
    out.append(h); out.append(body(lhs, rhs or {}))

out.append("#! fabric TM  correct={score} steps={steps}")
out.append("# Generated by gen_tm.py C=%d N=%d S=%g K=%d THETA=%g Q=%g NIN=%d -- do not edit." % (C, N, S, K, THETA, Q, NIN))
out.append("#threads 1")
out.append("^Bul")

# build (anchor = row 1, col 0)
rhs = {(0, c): "_" for c in range(1, NIN + 1)}; rhs[(0, SEP)] = "|"; rhs[(0, 1)] = ">"   # typing head for sample 1
for c in range(C):
    b = rowB(c) - 1
    rhs[(b, 0)] = "1"; rhs[(b, SEP)] = "|"
    for k in POSK: rhs[(b, k)] = fresh(N)
rhs[(NROW - 1, 0)] = state(0)
rule(header("B", "b", "#"), {}, rhs)

# typing: the head at (1, i) writes o/x and, for every clause, t/u at (rowA, i) and (rowA, SEP+i)
out.append("# typing")
for trig, ch, lit, neg in (("0", "o", "u", "t"), ("1", "x", "t", "u")):
    lits = {}
    for c in range(C):
        lits[(rowA(c) - 1, 0)] = lit; lits[(rowA(c) - 1, SEP)] = neg
    adv = dict(lits); adv[(0, 1)] = ">"
    rule(header(">", trig, ch, ctx="|"), {(0, 1): "!"}, adv)        # advance while east is not |
    rule(header(">", trig, ch), {(0, 1): "|"}, lits)                 # last bit: the head dies

# evaluate: clause output 1 -> 0 if an included automaton sits under an untrue literal
out.append("# evaluate")
for k in POSK:
    for s in range(N + 1, 2 * N + 1):
        rule(header("1", "i", "0"), {(0, k): fresh(s), (-1, k): "u"}, {})

# readout neuron at (NROW, 0): +1 per matched positive clause, -1 per matched negative
out.append("# readout")
def up_to(j):   return "Y" if j + 1 == K else state(j + 1)
def down_to(j): return "N" if j - 1 == -K else state(j - 1)
for j in range(-K + 1, K):
    for c in range(C):
        pos = c < C // 2
        rule(header(state(j), "o", up_to(j) if pos else down_to(j)), {(rowB(c) - NROW, 0): "1"}, {})
    rule(header(state(j), "o", down_to(j), weight=THETA), {}, {})

# teacher: mark the neuron and plant one feedback head per clause at (rowH, 0)
out.append("# teacher")
def heads(y, wrong):
    r = {}
    for c in range(C):
        pos = c < C // 2
        typ = "I" if (y == 1) == pos else "II"
        r[(rowH(c) - NROW, 0)] = PLANT[(typ, wrong)]
    return r
rule(header("Y", "p", "+", score=1), {}, heads(1, False)); rule(header("N", "p", "-"), {}, heads(1, True))
rule(header("N", "n", "+", score=1), {}, heads(0, False)); rule(header("Y", "n", "/"), {}, heads(0, True))
for j in range(-K + 1, K):
    rule(header(state(j), "p", "-"), {}, heads(1, True)); rule(header(state(j), "n", "+", score=1), {}, heads(0, False))

# feedback walk. A planted head at (rowH, 0) reads the clause output at (-1, 0) and becomes a
# walking head at (rowH, 1). A walking head at (rowH, k) reads the literal at (-2, 0) and the
# automaton at (-1, 0); it rewrites the automaton (step) or not (skip), and moves east.
out.append("# feedback")
def wt(pi):
    if pi >= 1: return BIG
    if pi <= 0: return None
    return pi / (1 - pi)
for (typ, wrong), g in PLANT.items():
    for o in (1, 0):
        rule(header(g, "f", "~"), {(-1, 0): str(o)}, {(0, 1): WALK[(typ, wrong, o)]})
for (typ, wrong, o), g in WALK.items():
    q = 1.0 if wrong else Q
    rule(header(g, "f", "~"), {(-1, 0): "|"}, {(0, 1): g})           # skip the separator column
    rule(header(g, "f", "~"), {(-1, 0): "~"}, {})                     # past the last automaton: die
    for s in range(1, 2 * N + 1):
        a = fresh(s); up = fresh(min(2 * N, s + 1)); dn = fresh(max(1, s - 1))
        for lit in "tu":
            # which step applies, with which probability
            if typ == "I":
                if o == 1: pi, tgt = ((S - 1) / S, up) if lit == "t" else (1 / S, dn)
                else:      pi, tgt = 1 / S, dn
            else:
                pi, tgt = (1.0, up) if (o == 1 and lit == "u" and s <= N) else (0.0, a)
            pi *= q
            w = wt(pi)
            lhs = {(-2, 0): lit, (-1, 0): a}
            if w is not None and tgt != a:
                rule(header(g, "f", "~", weight=w), lhs, {(-1, 0): tgt, (0, 1): g})
            if pi < 1:
                rule(header(g, "f", "~", weight=1), lhs, {(0, 1): g})

# clear
out.append("# clear")
rule(header("0", "c", "1"), {}, {})
for g in "YN+-/": rule(header(g, "c", state(0)), {}, {})
for j in range(-K + 1, K):
    if j: rule(header(state(j), "c", state(0)), {}, {})
rule(header("#", "c", "#", ctx=">"), {(0, 1): "!"}, {(0, 1): ">"})

open(OUT, "w", encoding="utf-8").write("\n".join(out) + "\n")
print("%s: %d rules, screen rows %d" % (OUT, sum(1 for l in out if l.startswith("=")), NROW + 2))
